#!/usr/bin/env python3
"""Generate normalized Q15 Lanczos-16 interpolation phases (no runtime libm)."""
import math
from pathlib import Path
def sinc(x):
    return 1.0 if abs(x) < 1e-12 else math.sin(math.pi*x)/(math.pi*x)
lines = ['// Generated by tools/generate_audio_sinc.py; Q15, 257 phases x 32 taps.',
         '#ifndef WYZAR_AUDIO_SINC_TABLE_H', '#define WYZAR_AUDIO_SINC_TABLE_H',
         'static constexpr int32_t audio_sinc[257][32] = {']
for phase in range(257):
    weights = []
    for tap in range(-15,17):
        x = tap-phase/256
        weights.append(sinc(x)*sinc(x/16) if abs(x)<16 else 0)
    total = sum(weights)
    row = [round(w/total*32768) for w in weights]
    row[15] += 32768-sum(row)
    lines.append('    {'+','.join(map(str,row))+'},')
lines += ['};','#endif','']
(Path(__file__).resolve().parents[1]/'user/audio_sinc_table.h').write_text('\n'.join(lines))
