#!/usr/bin/env python3
"""Bake Selawik's printable ASCII glyphs using system FreeType (no Python packages).

The generated header is checked in; normal OS builds do not need FreeType.
Run `make font-atlas` in WSL to regenerate it from the bundled, unmodified font.
"""
import ctypes as C
import ctypes.util
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/selawik/selawk.ttf'
OUTPUT = ROOT / 'src/gui/ui_font_data.h'

class Generic(C.Structure):
    _fields_ = [('data', C.c_void_p), ('finalizer', C.c_void_p)]
class Vector(C.Structure):
    _fields_ = [('x', C.c_long), ('y', C.c_long)]
class Bitmap(C.Structure):
    _fields_ = [('rows', C.c_uint), ('width', C.c_uint), ('pitch', C.c_int),
                ('buffer', C.POINTER(C.c_ubyte)), ('num_grays', C.c_ushort),
                ('pixel_mode', C.c_ubyte), ('palette_mode', C.c_ubyte), ('palette', C.c_void_p)]
class Metrics(C.Structure):
    _fields_ = [(name, C.c_long) for name in ('width', 'height', 'bearing_x', 'bearing_y',
                                             'advance', 'vert_x', 'vert_y', 'vert_advance')]
class Slot(C.Structure):
    _fields_ = [('library', C.c_void_p), ('face', C.c_void_p), ('next', C.c_void_p),
                ('index', C.c_uint), ('generic', Generic), ('metrics', Metrics),
                ('linear_x', C.c_long), ('linear_y', C.c_long), ('advance', Vector),
                ('format', C.c_uint), ('bitmap', Bitmap), ('left', C.c_int), ('top', C.c_int)]
class SizeMetrics(C.Structure):
    _fields_ = [('x_ppem', C.c_ushort), ('y_ppem', C.c_ushort)] + [
        (name, C.c_long) for name in ('x_scale', 'y_scale', 'ascender', 'descender', 'height', 'max_advance')]
class Size(C.Structure):
    _fields_ = [('face', C.c_void_p), ('generic', Generic), ('metrics', SizeMetrics)]
class Face(C.Structure):
    _fields_ = [(name, C.c_long) for name in ('num_faces', 'face_index', 'face_flags', 'style_flags', 'num_glyphs')] + [
        ('family', C.c_char_p), ('style', C.c_char_p), ('num_sizes', C.c_int), ('sizes', C.c_void_p),
        ('num_charmaps', C.c_int), ('charmaps', C.c_void_p), ('generic', Generic),
        ('bbox', C.c_long * 4), ('units', C.c_ushort)] + [
        (name, C.c_short) for name in ('ascender', 'descender', 'height', 'max_width', 'max_height', 'underline_y', 'underline_h')] + [
        ('glyph', C.POINTER(Slot)), ('size', C.POINTER(Size)), ('charmap', C.c_void_p)]

def main():
    library_path = ctypes.util.find_library('freetype')
    if not library_path:
        raise SystemExit('Install libfreetype6 to regenerate the atlas; normal builds use the checked-in header.')
    ft = C.CDLL(library_path)
    library = C.c_void_p()
    assert ft.FT_Init_FreeType(C.byref(library)) == 0
    face = C.POINTER(Face)()
    ft.FT_New_Face.argtypes = [C.c_void_p, C.c_char_p, C.c_long, C.POINTER(C.POINTER(Face))]
    assert ft.FT_New_Face(library, str(FONT).encode(), 0, C.byref(face)) == 0
    ft.FT_Set_Pixel_Sizes.argtypes = [C.POINTER(Face), C.c_uint, C.c_uint]
    ft.FT_Load_Char.argtypes = [C.POINTER(Face), C.c_ulong, C.c_int32]
    lines = ['// Generated by tools/bake_ui_font.py from Selawik 1.01. Do not edit.',
             '// Original font and SIL OFL license: assets/fonts/selawik/.',
             '// Source SHA256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
             '#ifndef WYZAR_UI_FONT_DATA_H', '#define WYZAR_UI_FONT_DATA_H']
    sizes = (12, 14, 16, 18, 21, 24, 28, 32)
    faces = []
    for pixels in sizes:
        assert ft.FT_Set_Pixel_Sizes(face, 0, pixels) == 0
        metrics = face.contents.size.contents.metrics
        ascent = (metrics.ascender + 63) // 64
        height = max((metrics.height + 63) // 64, ascent + (-metrics.descender + 63) // 64)
        bitmap, glyphs = bytearray(), []
        for code in range(32, 127):
            assert ft.FT_Load_Char(face, code, 4) == 0 # FT_LOAD_RENDER, normal grayscale hinting
            slot = face.contents.glyph.contents
            b = slot.bitmap
            assert b.pixel_mode == 2 or not b.width
            offset = len(bitmap)
            for row in range(b.rows):
                bitmap.extend(C.string_at(C.addressof(b.buffer.contents) + row * b.pitch, b.width))
            advance = (slot.advance.x + 32) // 64
            assert max(b.width, b.rows, advance, height, ascent) < 256
            assert -128 <= slot.left < 128 and -128 <= slot.top < 128
            glyphs.append((offset, b.width, b.rows, slot.left, slot.top, advance))
        lines.append(f'static const uint8_t ui_font_pixels_{pixels}[] = {{')
        lines.extend('    ' + ','.join(map(str, bitmap[i:i+32])) + ',' for i in range(0, len(bitmap), 32))
        lines.append('};')
        lines.append(f'static const UiGlyph ui_font_glyphs_{pixels}[95] = {{')
        lines.extend('    {' + ','.join(map(str, glyph)) + '},' for glyph in glyphs)
        lines.append('};')
        faces.append(f'    {{{pixels},{height},{ascent},ui_font_glyphs_{pixels},ui_font_pixels_{pixels}}},')
        print(f'Selawik {pixels}px: line height {height}, {len(bitmap)} coverage bytes')
    lines.extend(['static const UiFont ui_fonts[] = {', *faces, '};', '#endif', ''])
    OUTPUT.write_text('\n'.join(lines))
    ft.FT_Done_Face(face)
    ft.FT_Done_FreeType(library)

if __name__ == '__main__':
    main()
